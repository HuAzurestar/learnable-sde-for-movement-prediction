def test_saved_qualification_preserves_every_original_window_and_population(source, tmp_path):
    q = module._qualification(access(source,'final_eval_eligibility'), source=source,
        protocol=source['original']['protocol'], execution=source['execution'], output=tmp_path/'qualification')
    old = unpack(source['qualification'])
    new = unpack(q['qualification'])
    assert new['windows'] == old['windows']
    assert new['denominator_samples'] == old['denominator_samples']
    assert new['eligible_samples'] == old['eligible_samples']
    assert unpack(q['population'])['selection'] == unpack(source['args']['population'])['selection']
    assert new['execution_sha256'] == source['execution']['sha256']
    assert new['position_feature_value_prediction_metric_reads'] == 0
    for relative in new['windows'].values():
        assert read_json(tmp_path/'qualification'/relative) == read_json(source['source']/relative)


@pytest.mark.parametrize('fault',['scope','population','window','denominator'])
def test_rehashed_qualification_cannot_change_original_semantics(source,tmp_path,fault):
    bad = dict(source)
    q = deepcopy(unpack(source['qualification']))
    if fault=='scope': q['approval_sha256'] = digest('wrong approval')
    elif fault=='population': q['population_sha256'] = digest('wrong population')
    elif fault=='window': q['windows'] = {}
    else: q['denominator_samples'] += 1
    directory = tmp_path/'mutant-source'
    shutil.copytree(source['source'],directory)
    path, record = publish(directory,q)
    bad['item'] = dict(source['item'],directory=directory,manifest=dict(source['manifest'],qualification_path=str(path),
                                                  qualification_sha256=record['sha256']))
    with pytest.raises(ValueError):
        module._qualification(access(source,'final_eval_eligibility'), source=bad,
            protocol=source['original']['protocol'], execution=source['execution'], output=tmp_path/'q')


