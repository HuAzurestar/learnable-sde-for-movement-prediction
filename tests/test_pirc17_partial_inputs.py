def test_all_current_access_starts_and_saved_context_roundtrip_without_training(source,tmp_path,monkeypatch):
    args = source['args']
    events = []
    journal = tmp_path/'current-access'
    def software_guard(*,access_kind,protocol,execution,approval_sha256,operation,population_sha256=None,**kw):
        # Explicit authorization seam; this is NOT an actual human approval.
        _, event = publish(journal,dict(schema_version='pirc17-final-access-event-v1',event='started',
            attempt_id=f'{len(events)+1:032x}', at_utc='2026-10-03T00:00:00+00:00',
            access_kind=access_kind,protocol_sha256=protocol['sha256'],execution_sha256=execution['sha256'],
            approval_sha256=approval_sha256,population_sha256=population_sha256))
        events.append(access_kind)
        context = guard.VerifiedAccess(access_kind,'SYNTHETIC CLOSED INPUT',protocol['sha256'],
            execution['sha256'],approval_sha256,population_sha256,event['sha256'])
        return operation(context)
    monkeypatch.setattr(module.guard,'guarded_call',software_guard)
    monkeypatch.setattr(module,'_source_input',lambda *a:dict(source))
    encoder = source['prepared']['fits'].inputs.encoders['all-terrain']
    monkeypatch.setattr(module.CanonicalEncoder,'frozen_pirc22',lambda *a:encoder)
    def maps(access,*,original,execution,population,**kw):
        scope = dict(unpack(original['input_identity']), execution_sha256=execution['sha256'],
            population_sha256=population['sha256'],approval_sha256=access.approval_sha256)
        owner = fixture_maps(scope,source['prepared']['row'])
        owner.catalog = envelope(dict(unpack(original['map_catalog']),**{k:scope[k] for k in
            ('execution_sha256','population_sha256','approval_sha256')},access_started_sha256=access.access_started_sha256))
        return owner
    monkeypatch.setattr(module,'_maps',maps)
    monkeypatch.setattr(module.formal_training,'prepare_formal_training',lambda **kw:pytest.fail('raw training reload'))
    inputs = input_work.InputWork(protocol=args['protocol'],execution=source['execution'],matrix=args['matrix'],
        authority=dict(approval_path=None,approval_sha256=digest('EXPLICIT SOFTWARE APPROVAL ONLY'),test_path=None,
            review_path=None,journal_directory=journal), release=tmp_path,snapshot=tmp_path,data_root=tmp_path,
        trajectory_path=tmp_path/'NO-TRAJECTORY',development_eligibility_path=tmp_path/'NO-TRAINING')
    restored = inputs.restore_partial(envelope(dict(software_only=True)),output_directory=tmp_path/'output')
    try:
        value = read_json(restored.manifest['context_path'])
        assert context_semantic_identity(value) == context_semantic_identity(source['context'])
        assert events == ['final_eval_eligibility','final_eval_positions','final_eval_features','final_eval_features']
        current, _, details = input_work.read_input_work(restored.manifest,directory=tmp_path/'output',
            protocol=args['protocol'],execution=source['execution'],matrix=args['matrix'],
            approval_sha256=inputs.authority['approval_sha256'],access_journal=journal)
        assert details['actual_access_events_verified'] and not details['raw_sources_independently_reloaded']
        assert current['prior'].evidence == args['prior'].evidence
        assert not hasattr(restored.training,'methods') and not hasattr(restored.training,'terrain')
        assert restored.source_context_reference['content_sha256'] == source['context']['sha256']
        with pytest.raises(ValueError,match='retry'):inputs.restore_partial({},output_directory=tmp_path/'another')
    finally:
        restored.close()


