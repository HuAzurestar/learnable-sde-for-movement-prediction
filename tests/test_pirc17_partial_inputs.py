def test_source_input_uses_pinned_scientific_tip_for_closed_cap_costs(source, monkeypatch):
    """Transport orchestration seam; no claim of real source/Job qualification."""
    args = source['args']
    work = next(w for w in unpack(args['matrix'])['workloads'] if w['kind'] == 'input_qualification_and_population')
    tip = dict(root_sha256=digest('SOFTWARE ROOT'), event_count=1, last_event_sha256=digest('SOFTWARE TIP'))
    completed = dict(result_sha256=digest('SOFTWARE RESULT'), settlement_sha256=digest('SOFTWARE SETTLEMENT'),
        observation_sha256=digest('SOFTWARE OBSERVATION'), controller_elapsed_ns=1, artifact=None)
    item = dict(source['item'], **{k: completed[k] for k in
        ('result_sha256', 'settlement_sha256', 'observation_sha256', 'controller_elapsed_ns')})
    cost = dict(ledger_tip=tip, approval_sha256=unpack(args['input_identity'])['approval_sha256'])
    saved = dict(committed_tip=tip, completed_sources={work['work_id']: completed}, context_sha256=source['context']['sha256'])
    monkeypatch.setattr(module.predecessor, '_history', lambda binding:
        (dict(ledger_directory=str(source['root'])), cost, saved, source['original'], dict(software_only=True)))
    calls = []
    class Closed:
        def __init__(self, directory, *, contract, tip):
            calls.append(tip)
        def read(self, requested):
            assert requested == work
            return item
    monkeypatch.setattr(module, 'ClosedOutputs', Closed)
    result = module._source_input(envelope(dict(SOFTWARE_ONLY=True)), args['protocol'], args['matrix'])
    assert calls == [tip] and result['item'] == item
