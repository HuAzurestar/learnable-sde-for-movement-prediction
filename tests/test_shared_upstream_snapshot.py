def snapshot_fixture(tmp_path, *, terrain=False):
    value = {'schema_version': 'synthetic-upstream-metadata-v1', 'status': 'accepted-control'}
    if terrain:
        value.update(final_eval_read_count=0, source_selection_identity_sha256=digest('synthetic selection'),
                     immutability_policy='new_selection_version_required', status='selected')
    path = tmp_path / 'metadata.json'
    path.write_bytes(json.dumps(value).encode())
    record = {'object_id': 'selection' if terrain else 'metadata', 'issue': 'synthetic-control',
              'acceptance_commit': hashlib.sha1(b'explicit synthetic acceptance control, not a real ref').hexdigest(),
              'code_sha': hashlib.sha1(b'explicit synthetic upstream code control').hexdigest(),
              'schema_version': value['schema_version'], 'artifact_hash': hashlib.sha256(path.read_bytes()).hexdigest(),
              'artifact_size_bytes': path.stat().st_size, 'path': path.name, 'format': 'json-metadata',
              'role': 'metadata-only', 'kind': 'terrain-selection' if terrain else 'metadata',
              'data_hash': digest('synthetic dataset'), 'split_hash': digest('synthetic split'),
              'fold_hash': digest('synthetic fold'), 'feature_hash': digest('synthetic features'),
              'selection_hash': value.get('source_selection_identity_sha256', {'not_applicable': 'no selection in metadata control'}),
              'license': {'id': 'synthetic-control', 'scope': 'metadata-only'},
              'metadata_checks': value, 'source_branch': 'display-only-control'}
    # This explicit test catalog is an operator-provided synthetic control,
    # never a claim that these newly generated bytes were accepted upstream.
    accepted = [{'status': 'accepted', 'input': deepcopy(record)}]
    cutover = {'mode': 'adopted_primary', 'selection_hash': record['selection_hash']} if terrain else {'mode': 'not_applicable'}
    manifest = {'schema_version': 'pirc25-upstream-snapshot-v1', 'inputs': [record],
                'studies': [{'study_id': 'synthetic-study', 'pirc22_cutover': cutover}],
                'cells': [{'cell_id': 'dependent', 'study_id': 'synthetic-study', 'role': 'primary',
                           'upstream_ids': [record['object_id']]},
                          {'cell_id': 'independent', 'study_id': 'independent-study', 'role': 'primary', 'upstream_ids': []}]}
    manifest['studies'].append({'study_id': 'independent-study', 'pirc22_cutover': {'mode': 'not_applicable'}})
    return path, manifest, accepted


def resolve(manifest, tmp_path, accepted):
    resolver = getattr(upstream, 'resolve_snapshot', None)
    assert callable(resolver), 'Confirmed parent SOL-001 resolve_snapshot is missing'
    return resolver(manifest, root=tmp_path, accepted_versions=accepted)


def cells(result):
    return {cell['cell_id']: cell for cell in result['cells']}


def test_full_snapshot_receipt_keeps_all_declared_identities_and_no_data_permission(tmp_path):
    path, manifest, accepted = snapshot_fixture(tmp_path)
    result = resolve(manifest, tmp_path, accepted)
    assert not result['rejected_inputs'] and result['data_authorization'] == 'none'
    actual = result['resolved'][0]
    for field in ('issue', 'acceptance_commit', 'code_sha', 'schema_version', 'artifact_hash', 'artifact_size_bytes',
                  'data_hash', 'split_hash', 'fold_hash', 'feature_hash', 'selection_hash', 'license'):
        assert actual[field] == manifest['inputs'][0][field]
    assert actual['last_validated_at'] and actual['physical_size_bytes'] == path.stat().st_size
    assert cells(result)['dependent']['status'] == cells(result)['independent']['status'] == 'ready'


@pytest.mark.parametrize('failure,code', [('missing', 'MISSING_ARTIFACT'), ('hash', 'IDENTITY_MISMATCH'),
                                        ('size', 'IDENTITY_MISMATCH'), ('unaccepted', 'UNACCEPTED_VERSION'),
                                        ('code', 'UNACCEPTED_VERSION'), ('schema', 'IDENTITY_MISMATCH')])
def test_actual_input_rejection_blocks_only_the_registered_dependent_cell(tmp_path, failure, code):
    path, manifest, accepted = snapshot_fixture(tmp_path)
    if failure == 'missing':
        path.unlink()
    elif failure == 'hash':
        path.write_bytes(path.read_bytes().replace(b'accepted-control', b'rejected-control'))
    elif failure == 'size':
        manifest['inputs'][0]['artifact_size_bytes'] += 1
        accepted[0]['input']['artifact_size_bytes'] += 1
    elif failure == 'unaccepted':
        accepted[0]['status'] = 'pending'
    elif failure == 'code':
        manifest['inputs'][0]['code_sha'] = hashlib.sha1(b'an unaccepted synthetic version').hexdigest()
    else:
        manifest['inputs'][0]['schema_version'] = 'other-schema'
        manifest['inputs'][0]['metadata_checks']['schema_version'] = 'other-schema'
        accepted[0]['input'] = deepcopy(manifest['inputs'][0])
    result = resolve(manifest, tmp_path, accepted)
    assert result['rejected_inputs'][0]['code'] == code
    assert cells(result)['dependent']['status'] == 'rejected'
    assert cells(result)['independent']['status'] == 'ready'
    assert cells(result)['dependent']['upstream_ids'] == ['metadata'], 'No fallback or route reclassification'


def test_source_branch_is_display_only_not_snapshot_or_acceptance_identity(tmp_path):
    _, manifest, accepted = snapshot_fixture(tmp_path)
    first = resolve(manifest, tmp_path, accepted)
    changed = deepcopy(manifest)
    changed['inputs'][0]['source_branch'] = 'a-different-display-branch'
    second = resolve(changed, tmp_path, accepted)
    assert first['snapshot_hash'] == second['snapshot_hash']
    assert not second['rejected_inputs'] and second['resolved'][0]['source_branch'] == 'a-different-display-branch'


