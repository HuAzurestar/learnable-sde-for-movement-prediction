@pytest.mark.parametrize('valid', [True, False])
def test_large_actual_json_hash_and_schema_projection_do_not_allocate_whole_file(tmp_path, monkeypatch, valid):
    path, manifest, accepted = snapshot_fixture(tmp_path)
    chunk = b'x' * (1024 * 1024)
    hasher = hashlib.sha256()
    with path.open('wb') as target:
        for part in [b'{"schema_version":"synthetic-upstream-metadata-v1","status":"accepted-control","payload":"']:
            target.write(part)
            hasher.update(part)
        for _ in range(20):
            target.write(chunk)
            hasher.update(chunk)
        target.write(b'"}')
        hasher.update(b'"}')
    record = manifest['inputs'][0]
    record.update(artifact_hash=hasher.hexdigest() if valid else '0' * 64, artifact_size_bytes=path.stat().st_size)
    accepted[0]['input'] = deepcopy(record)
    reads = []
    observe_file(monkeypatch, path, before_read=lambda actual, size: reads.append(size))
    # Collection, fixture creation and observation helpers precede measurement.
    tracemalloc.start()
    try:
        result = resolve(manifest, tmp_path, accepted)
        _, peak = tracemalloc.get_traced_memory()
    finally:
        tracemalloc.stop()
    assert reads and all(0 < size <= 1024 * 1024 for size in reads)
    assert peak < 4 * 1024 * 1024, f'Whole metadata allocation: actual traced peak {peak}'
    assert bool(result['rejected_inputs']) != valid
    assert cells(result)['dependent']['status'] == ('ready' if valid else 'rejected')


def test_immutable_takeover_definition_and_validation_receipt_are_published_outside_git(tmp_path):
    _, manifest, accepted = snapshot_fixture(tmp_path)
    snapshot_type = getattr(upstream, 'UpstreamSnapshot', None)
    assert snapshot_type is not None, 'Confirmed parent SOL-001 UpstreamSnapshot is missing'
    snapshot = snapshot_type(manifest)
    store = ResearchStore(tmp_path / 'runtime', 'snapshot-control', initialize=True)
    result = snapshot.register(store, root=tmp_path, accepted_versions=accepted)
    assert store.manifest('upstream-snapshot-' + result['snapshot_hash']) == snapshot.definition
    receipt = store.manifest('upstream-validation-' + result['receipt_hash'])
    assert digest(receipt) == result['receipt_hash'] and receipt['snapshot_hash'] == result['snapshot_hash']
    assert receipt['data_authorization'] == 'none'
    assert not any(event['event_kind'].startswith('READ_') for event in store.events())


